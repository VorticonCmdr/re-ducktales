const PORTS = new Set([
  0x563, 0x56a, 0x572, 0x57a, 0x57e, 0x70d, 0x714, 0x71c, 0x724, 0x728, 0x78a,
  0x791, 0x79c, 0x7a0, 0x7ed, 0x7ff, 0x812, 0x5fa, 0x601, 0x60c, 0x610, 0x647,
]);
const signed = (v) => (v << 16) >> 16;
export function egaDriverLineWork(kind, args, { instruction = null } = {}) {
  const ips = IPS[kind],
    expected = { point: 2, vertical: 3, horizontal: 3, diagonal: 8 }[kind];
  if (
    !ips ||
    !Array.isArray(args) ||
    args.length !== expected ||
    args.some((v) => !Number.isInteger(v) || v < -32768 || v > 65535)
  )
    throw Error("Unsupported EGA line arguments");
  if (instruction !== null && typeof instruction !== "function")
    throw Error("Invalid line work observer");
  let instructions = 0,
    portWrites = 0;
  function block(lo, hi = lo) {
    const a = ips.indexOf(lo),
      b = ips.indexOf(hi);
    if (a < 0 || b < a) throw Error("Invalid EGA line source block");
    instructions += b - a + 1;
    for (let i = a; i <= b; i++) {
      if (PORTS.has(ips[i])) portWrites++;
      instruction?.(ips[i]);
    }
  }
  const finish = () => ({
    instructions,
    portWrites,
    repeatOpcodes: 0,
    repeatIterations: 0,
  });
  if (kind === "point") {
    const [y, x] = args.map(signed);
    block(0x515, 0x522);
    if (x >= 0) {
      block(0x524, 0x527);
      if (x < 320) {
        block(0x529, 0x52b);
        if (y >= 0) {
          block(0x52d, 0x531);
          if (y < 200) block(0x533, 0x57f);
        }
      }
    }
    block(0x581, 0x586);
    return finish();
  }
  if (kind === "vertical") {
    let [end, start, x] = args.map(signed);
    const done = () => {
      block(0x736, 0x73c);
      return finish();
    };
    block(0x69b, 0x6ae);
    if (x < 0) {
      block(0x6b0);
      return done();
    }
    block(0x6b3, 0x6b6);
    if (x >= 320) return done();
    block(0x6b8, 0x6be);
    if (start >= end) {
      block(0x6c0);
      [start, end] = [end, start];
    }
    block(0x6c1, 0x6c3);
    if (start < 0) {
      block(0x6c5);
      start = 0;
    }
    block(0x6c7, 0x6ca);
    if ((start & 65535) >= 200) return done();
    block(0x6cc, 0x6ce);
    if (end < 0) return done();
    block(0x6d0, 0x6d4);
    if (end >= 200) {
      block(0x6d6);
      end = 200;
    }
    block(0x6d9, 0x72e);
    // Original clamps the inclusive end to200, not199. Preserve its extra row.
    for (let n = end - start + 1; n > 0; n--) block(0x730, 0x734);
    return done();
  }
  if (kind === "horizontal") {
    let [y, end, start] = args.map(signed);
    const done = () => {
      block(0x815, 0x81c);
      return finish();
    };
    const clipped = () => {
      block(0x758);
      return done();
    };
    block(0x73f, 0x756);
    if (y < 0) return clipped();
    block(0x75b, 0x75d);
    if (y >= 200) return clipped();
    block(0x75f, 0x763);
    if (start >= end) {
      block(0x765);
      [start, end] = [end, start];
    }
    block(0x766, 0x768);
    if (start < 0) {
      block(0x76a);
      start = 0;
    }
    block(0x76c, 0x771);
    if ((start & 65535) >= 320) return clipped();
    block(0x773, 0x775);
    if (end < 0) return clipped();
    block(0x777, 0x779);
    if (end >= 320) {
      block(0x77b, 0x77d);
      end = 319;
    }
    block(0x77e, 0x7cb);
    let remaining = end - start + 1;
    const shift = start & 7;
    if (shift) {
      block(0x7cd, 0x7de);
      remaining -= 8 - shift;
      if (remaining < 0) {
        block(0x7e0);
        do {
          block(0x7e2, 0x7e7);
          remaining++;
        } while (remaining !== 0);
      }
      block(0x7e9, 0x7f0);
    }
    block(0x7f1, 0x7f9);
    if (remaining >>> 3 > 0) {
      block(0x7fb, 0x7ff);
      for (let n = remaining >>> 3; n > 0; n--) block(0x800, 0x803);
    }
    block(0x805, 0x813);
    return done();
  }
  let [axis, majorStep, minorStep, count, twiceMajor, twiceMinor, y, x] =
    args.map(signed);
  if (
    ![0, 1].includes(axis) ||
    ![-1, 1].includes(majorStep) ||
    ![-1, 1].includes(minorStep) ||
    count < 1 ||
    count > 32767
  )
    throw Error("Unsupported diagonal source path");
  block(0x589, 0x5a1);
  if ((minorStep & 255) === 255) block(0x5a3);
  block(0x5a5, 0x5c7);
  if (axis) block(0x5c9, 0x5d0);
  else block(0x5d2);
  block(0x5d9, 0x617);
  let error = signed(twiceMinor - count);
  for (let n = 0; n < count; n++) {
    block(0x619, 0x61e);
    if (x >= 0) {
      block(0x620, 0x623);
      if (x < 320) {
        block(0x625, 0x62a);
        if (y >= 0) {
          block(0x62c, 0x630);
          if (y < 200) block(0x632, 0x648);
        }
      }
    }
    block(0x64a, 0x64e);
    let step = 0;
    if (error > 0) {
      block(0x650, 0x651);
      step = minorStep;
      error = signed(error - twiceMajor);
    }
    block(0x655);
    error = signed(error + twiceMinor);
    block(0x659);
    if (axis) {
      block(0x65b);
      if (step) {
        block(0x65d, 0x660);
        if (step < 0) block(0x662);
        block(0x664, 0x666);
      }
      block(0x669, 0x671);
      if (n === count - 1) block(0x673);
      x = signed(x + majorStep);
      y = signed(y + step);
    } else {
      block(0x675, 0x680);
      // This branch reloads the major step, not the minor error correction.
      block(0x682, 0x685);
      if (majorStep < 0) block(0x687);
      block(0x689, 0x68b);
      block(0x68e, 0x68f);
      x = signed(x + step);
      y = signed(y + majorStep);
    }
  }
  block(0x691, 0x698);
  return finish();
}

// Resident140e:00b0 dispatch, EGA DS2046=0. These are primitive counts only;
// the resident's own instructions/color-setting work are not included.
export function egaLinePrimitiveWork({ x, y, x2, y2 }, scaleMode = 0) {
  if (
    scaleMode !== 0 ||
    [x, y, x2, y2].some((v) => !Number.isInteger(v) || v < -32768 || v > 32767)
  )
    throw Error("Unsupported resident line coordinate/mode");
  if (
    (x < 0 && x2 < 0) ||
    (x >= 320 && x2 >= 320) ||
    (y < 0 && y2 < 0) ||
    (y >= 200 && y2 >= 200)
  )
    return {
      kind: "rejected",
      args: [],
      instructions: 0,
      portWrites: 0,
      repeatOpcodes: 0,
      repeatIterations: 0,
    };
  let kind, args;
  if (x === x2) {
    if (y === y2) {
      kind = "point";
      args = [y, x];
    } else {
      kind = "vertical";
      args = [y2, y, x];
    }
  } else if (y === y2) {
    kind = "horizontal";
    args = [y, x2, x];
  } else {
    const dx = Math.abs(x2 - x),
      dy = Math.abs(y2 - y);
    if (dx >= 32768 || dy >= 32768)
      throw Error("Unsupported resident line difference overflow");
    const horizontal = dx >= dy,
      major = horizontal ? dx : dy,
      minor = horizontal ? dy : dx;
    kind = "diagonal";
    args = [
      horizontal ? 1 : 0,
      horizontal ? Math.sign(x2 - x) : Math.sign(y2 - y),
      horizontal ? Math.sign(y2 - y) : Math.sign(x2 - x),
      major,
      (2 * major) & 65535,
      (2 * minor) & 65535,
      y,
      x,
    ];
  }
  return { kind, args, ...egaDriverLineWork(kind, args) };
}
