import { waitForScene } from "./helpers/scene.js";
import { test, expect } from "@playwright/test";
import { nextRandom } from "../../src/game/integer.js";
import { finishSecurityEntry } from "./helpers/security.js";
import { exploreFlight } from "./helpers/flight-policy.js";
import { openRecordedApplication } from "./helpers/clock.js";

test("photography keyboard target shot, results, campaign return and collected notice", async ({
  page,
}) => {
  test.setTimeout(120000);
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  await openRecordedApplication(page, 1);
  await expect(page.locator("#actions")).toBeVisible();
  const canvas = page.locator("#game");
  const state = () => canvas.getAttribute("data-state").then(JSON.parse);
  // Explicit authored device profile for this acceptance case. The production
  // browser receives OS repeat makes; no game timer synthesizes held keys.
  let repeatedKey = null;
  async function until(predicate, max = 4000) {
    for (let i = 0; i < max; i++) {
      const s = await state();
      if (s?.diagnostic) throw Error(s.diagnostic);
      if (s && predicate(s)) return s;
      const step = repeatedKey ? Math.min(8, repeatedKey.remaining) : 8;
      await page.clock.runFor(step);
      if (repeatedKey) {
        repeatedKey.remaining -= step;
        if (repeatedKey.remaining === 0) {
          await page.keyboard.down(repeatedKey.key);
          repeatedKey.remaining = 32;
        }
      }
    }
    throw Error(
      `unfinished photography browser wait: ${JSON.stringify(await state())}`,
    );
  }
  async function press(key) {
    await page.keyboard.press(key);
    await page.clock.runFor(100);
  }
  await until((s) => s.scene === "title");
  await canvas.focus();
  await press("Space");
  await waitForScene(page, canvas, "difficulty");
  await press("Enter");
  await waitForScene(page, canvas, "office");
  await page.getByRole("checkbox", { name: "Sound (reconstructed)" }).check();
  await page.locator("#map").click();
  await finishSecurityEntry({ page, until, state });
  const bounds = await canvas.boundingBox();
  await canvas.click({
    position: { x: (bounds.width * 46) / 320, y: (bounds.height * 56) / 200 },
  });
  await page.clock.runFor(100);
  await press("Space");
  await until((s) => s.campaign.destination?.ready);
  await press("ArrowRight");
  await until((s) => s.campaign.choice === 1 && s.campaign.destination?.ready);
  await press("Space");
  await exploreFlight({ page, state, until });
  const arrived = await until(
    (s) => s.scene === "photography" && s.photography.phase === "playing",
  );
  // Security changes the first race roll. Require a real landing and race win
  // before photography; a crash would award this destination to Glomgold.
  expect(arrived.flight.outcome.code).toBe(1);
  expect(arrived.flight.phase).toBe("complete");
  const day = arrived.campaign.day,
    location = arrived.campaign.location,
    money = arrived.money;
  // A real player chooses a visible target, aims, then fires. This adaptive UI
  // acceptance path is separate from fixed-stream deterministic regressions.
  let targetShot = false,
    shots = 0;
  while (shots < 8 && !targetShot) {
    const ready = await until(
      (s) =>
        s.scene !== "photography" ||
        s.photography.phase !== "playing" ||
        s.photography.animals.some(
          (a) => a.place && a.animal === s.photography.target && a.frame === 0,
        ),
    );
    expect(ready.scene).toBe("photography");
    expect(ready.photography.phase).toBe("playing");
    const column = ready.photography.animals.findIndex(
        (a) =>
          a.place && a.animal === ready.photography.target && a.frame === 0,
      ),
      key = ["ArrowLeft", "ArrowUp", "ArrowRight"][column];
    await page.keyboard.down(key);
    await until((s) => s.photography.column === column);
    await page.keyboard.up(key);
    const before = await state(),
      count = before.photography.photoCount;
    await page.keyboard.down("Space");
    await until(
      (s) =>
        s.photography.photoCount > count || s.photography.phase !== "playing",
    );
    await page.keyboard.up("Space");
    shots++;
    targetShot = (await state()).photography.photos.includes(
      ready.photography.target,
    );
  }
  expect(targetShot).toBe(true);
  // Speaker output is generated by the worklet;HTMLMediaElement.readyState
  // stays0 because no audio-file URL is assigned. Observe actual device output.
  await expect
    .poll(() =>
      page.locator("#sound").evaluate((a) => Number(a.dataset.signalSamples)),
    )
    .toBeGreaterThan(0);
  expect(await page.locator("#sound").getAttribute("data-context-state")).toBe(
    "running",
  );
  const shot = await state();
  expect(shot.photography.film).toBeLessThan(12);
  await canvas.screenshot({
    path: test.info().outputPath("photography-shot.png"),
  });
  // Spend all remaining film with explicit physical repeat makes: first after
  //250ms,then every32ms. These are authored external inputs,not native typematic
  // evidence or fitted timer values; source mode1 flushes every ordinary read.
  await page.keyboard.down("Space");
  repeatedKey = { key: "Space", remaining: 250 };
  const results = await until(
    (s) => s.scene === "photography" && s.photography.phase === "results",
    10000,
  );
  repeatedKey = null;
  await page.keyboard.up("Space");
  expect(results.photography.film, "All film consumed by physical makes").toBe(
    -1,
  );
  expect(results.photography.photoCount).toBe(12);
  const score = results.photography.photos.reduce(
    (sum, p) => sum + (p === results.photography.target ? 500 : p ? 50 : 0),
    0,
  );
  expect(score).toBeGreaterThanOrEqual(500);
  await until(
    (s) =>
      s.scene === "photography" &&
      s.photography.phase === "results" &&
      s.photography.wait?.clock === "driver",
  );
  await canvas.screenshot({
    path: test.info().outputPath("photography-results.png"),
  });
  const returned = await until((s) => s.scene === "map", 6000);
  expect(returned.money).toBe(money + score);
  expect(returned.campaign.day).toBe(day + 2);
  expect(returned.campaign.playerCollected).toContain(location);
  expect(returned.photography.outcome.code).toBe(1);
  const preserved = {
    money: returned.money,
    day: returned.campaign.day,
    // The visit's two root dispatches include one normal rival claim (3 draws).
    seed: nextRandom(nextRandom(nextRandom(returned.seed))),
  };
  await page.evaluate(() => {
    window.photographyReportAudio = [];
    document.addEventListener("gameaudio", (event) =>
      window.photographyReportAudio.push(event.detail),
    );
  });
  const afterBounds = await canvas.boundingBox();
  await canvas.click({
    position: {
      x: (afterBounds.width * 46) / 320,
      y: (afterBounds.height * 56) / 200,
    },
  });
  await page.clock.runFor(100);
  await press("Space");
  const report = await until((s) => s.scene === "rival-report", 3000);
  // Entry precedes portrait/reveal and the first fresh device-status query.
  expect(report.rivalReport.busy).toBeNull();
  expect(report.rivalReport.phase).toBe("speech");
  let observedNotice = false;
  // Explicit conditional host20ms/Game16ms profile. Device completion is real,
  // never injected;game time is independent of the browser audio clock.
  for (let i = 0; i < 1000; i++) {
    const current = await state();
    if (current.diagnostic) throw Error(current.diagnostic);
    if (current.scene === "visit-notice") {
      expect(current.visitNotice.reason).toBe("player");
      observedNotice = true;
    }
    if (current.scene === "map") break;
    if (i === 999)
      throw Error("Unfinished Safari collected-notice audio route");
    await new Promise((resolve) => setTimeout(resolve, 20));
    await page.clock.runFor(16);
  }
  expect(observedNotice).toBe(true);
  const audioEvents = await page.evaluate(() => window.photographyReportAudio);
  const speech = audioEvents.find(
    (e) => e.type === "ack" && e.argument === 0x6e && !e.query,
  );
  expect(speech).toBeDefined();
  const queries = audioEvents.filter(
    (e) =>
      e.type === "ack" &&
      e.query &&
      e.token.startsWith(speech.token + ":status:"),
  );
  expect(queries.length).toBeGreaterThan(0);
  expect(queries.map((e) => e.token)).toEqual(
    queries.map((_, i) => `${speech.token}:status:${i + 1}`),
  );
  expect(
    audioEvents.some(
      (e) =>
        e.type === "complete" && e.token === speech.token && e.busy === false,
    ),
  ).toBe(true);
  const reset = audioEvents.find(
    (e) => e.type === "ack" && e.argument === 0x21 && !e.query,
  );
  expect(reset).toBeDefined();
  expect(
    queries.every(
      (e) => e.sequence > speech.sequence && e.sequence < reset.sequence,
    ),
  ).toBe(true);
  const repeat = await state();
  expect({
    money: repeat.money,
    day: repeat.campaign.day,
    seed: repeat.seed,
  }).toEqual(preserved);
  await page.locator("#restart").click();
  await page.clock.runFor(100);
  expect((await state()).photography).toBeNull();
  expect((await state()).scene).toBe("title");
  expect(errors).toEqual([]);
  await expect(page.locator("#diagnostic")).toBeHidden();
});
